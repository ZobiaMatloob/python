# Lists are ordered collections of items that can be changed (mutable)
# . They are defined using square brackets [].
#Example 1:
my_list = [1, 2, 3, 4, 5]
print(my_list)

#Example 2:
my_list[4] = 10
print(my_list)
#This code example demonstrates list item modification using index assignment in Python Lists.
#  It changes the value of an existing element inside a list and then prints the updated list 
# to the console.

#Example 3:
my_list = ["big", "small", "medium"]
print(len(my_list))
