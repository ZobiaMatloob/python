# Dictionary class for storing key-value pairs with various utility methods.
# Example 1:
my_dict = {"name": "Alina", "age": 30, "city": "Lahore"}
print(my_dict)

# Example 2:
my_dict["age"] = 31
print(my_dict)
# This code example demonstrates dictionary item modification using key assignment in Python Dictionaries.
# It changes the value of an existing key-value pair inside a dictionary and 
# then prints the updated dictionary to the console.

# Example 3:
my_dict = {"name": "Alina", "age": 30, "city": "Lahore"}
print(len(my_dict))
# To get the length of a dictionary in Python, you can use the built-in len() function.

# Example 4:
my_dict = {"name": "Alina", "age": 30, "city": "Lahore"}
print(my_dict["name"])  # Accessing the value associated with the key "name"

# Example 5:
my_dict = {"name": "Alina", "age": 30, "city": "Lahore"}
print(my_dict.get("name"))  # Accessing the value associated with the key "name" using the get() method