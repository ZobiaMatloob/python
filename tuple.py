# tuple are immutable data types in Python. Once a tuple is created,
#  its elements cannot be changed, added, or removed. 
# Tuples are defined by enclosing elements in parentheses ().
# Example 1:
my_tuple = (1, 2, 3, 4, 5)
print(my_tuple)

# Example 2:
my_tuple = ("big", "small", "medium")
print(len(my_tuple))
# To get the length of a tuple in Python, you can use the built-in len() function.

# Example 3:
my_tuple = (1, 2, 3)
print(my_tuple[0])  # Accessing the first element of the tuple because
# indexing starts at 0 in Python.

# Example 4:
my_tuple = (1, 2, 3)
print(my_tuple[-1])  # Accessing the last element of the tuple because
# negative indexing starts from the end in Python.
