# Data types in Python

x = type(12)                                   #integer
y = type(20.5)                                 #float
k = type(1j)                                   #complex
z = type("Hello World")                        #string
l = type(True)                                 #boolean
j = type(["berry", "strawberry", "grape"])     #list
g = type({'apple', 'banana', 'cherry'})        #set
a = type({'name': 'John', 'age': 36})          #dictionary

print(x)
print(y)
print(k)
print(z)
print(l)
print(j)
print(g)
print(a)